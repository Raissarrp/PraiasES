CREATE TABLE IF NOT EXISTS fontes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL UNIQUE,
  tipo text,
  url text,
  criado_em timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS municipios (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  uf char(2) NOT NULL DEFAULT 'ES',
  criado_em timestamptz NOT NULL DEFAULT now(),
  UNIQUE (nome, uf)
);

CREATE TABLE IF NOT EXISTS praias (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  municipio_id bigint NOT NULL REFERENCES municipios(id),
  nome text NOT NULL,
  criado_em timestamptz NOT NULL DEFAULT now(),
  UNIQUE (municipio_id, nome)
);

CREATE TABLE IF NOT EXISTS documentos_fonte (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fonte_id bigint NOT NULL REFERENCES fontes(id),
  nome_arquivo text NOT NULL,
  identificador text,
  data_publicacao timestamptz,
  caminho_origem text,
  criado_em timestamptz NOT NULL DEFAULT now(),
  UNIQUE (fonte_id, nome_arquivo)
);

CREATE TABLE IF NOT EXISTS pontos_monitoramento (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  municipio_id bigint NOT NULL REFERENCES municipios(id),
  praia_id bigint REFERENCES praias(id),
  codigo text NOT NULL,
  descricao text,
  tipo_ponto text NOT NULL CHECK (tipo_ponto IN ('praia', 'efluente')),
  utm_e numeric,
  utm_s numeric,
  criado_em timestamptz NOT NULL DEFAULT now(),
  UNIQUE (municipio_id, codigo, tipo_ponto)
);

CREATE TABLE IF NOT EXISTS amostras_balneabilidade (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fonte_id bigint NOT NULL REFERENCES fontes(id),
  documento_fonte_id bigint REFERENCES documentos_fonte(id),
  ponto_id bigint NOT NULL REFERENCES pontos_monitoramento(id),
  id_amostra text NOT NULL,
  id_relatorio text,
  pagina integer,
  data_coleta date NOT NULL,
  hora_coleta time,
  algas boolean,
  banhistas boolean,
  lixo boolean,
  condicoes_meteorologicas_24h text,
  condicoes_meteorologicas_momento text,
  data_publicacao timestamptz,
  temperatura_ambiente numeric,
  coliformes_nmp_100ml numeric,
  plano_amostragem text,
  laboratorio text,
  problemas_validacao text,
  criado_em timestamptz NOT NULL DEFAULT now(),
  UNIQUE (fonte_id, id_amostra)
);

CREATE TABLE IF NOT EXISTS chuva (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  municipio_id bigint REFERENCES municipios(id),
  fonte_id bigint REFERENCES fontes(id),
  data_registro date NOT NULL,
  volume numeric,
  unidade text,
  observacoes text,
  criado_em timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS saneamento (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  municipio_id bigint REFERENCES municipios(id),
  fonte_id bigint REFERENCES fontes(id),
  data_referencia date,
  indicador text NOT NULL,
  valor numeric,
  unidade text,
  observacoes text,
  criado_em timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_praias_municipio ON praias (municipio_id);
CREATE INDEX IF NOT EXISTS idx_pontos_municipio ON pontos_monitoramento (municipio_id);
CREATE INDEX IF NOT EXISTS idx_pontos_praia ON pontos_monitoramento (praia_id);
CREATE INDEX IF NOT EXISTS idx_amostras_ponto_data ON amostras_balneabilidade (ponto_id, data_coleta);
CREATE INDEX IF NOT EXISTS idx_documentos_fonte ON documentos_fonte (fonte_id);

CREATE OR REPLACE FUNCTION importar_amostras_csv(
  p_registros jsonb,
  p_nome_arquivo text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  registro jsonb;
  fonte_id_local bigint;
  documento_id_local bigint;
  municipio_id_local bigint;
  praia_id_local bigint;
  ponto_id_local bigint;
  amostra_existente boolean;
  inseridos integer := 0;
  ignorados integer := 0;
BEGIN
  IF jsonb_typeof(p_registros) <> 'array' OR jsonb_array_length(p_registros) = 0 THEN
    RAISE EXCEPTION 'A lista de registros não pode ser vazia';
  END IF;

  INSERT INTO fontes (nome, tipo)
  VALUES ('Prefeitura de Vitória', 'fonte ambiental')
  ON CONFLICT (nome) DO UPDATE SET tipo = EXCLUDED.tipo
  RETURNING id INTO fonte_id_local;

  INSERT INTO documentos_fonte (fonte_id, nome_arquivo)
  VALUES (fonte_id_local, p_nome_arquivo)
  ON CONFLICT (fonte_id, nome_arquivo) DO UPDATE SET nome_arquivo = EXCLUDED.nome_arquivo
  RETURNING id INTO documento_id_local;

  SELECT id INTO municipio_id_local
  FROM municipios
  WHERE nome = 'Vitória' AND uf = 'ES';

  IF municipio_id_local IS NULL THEN
    INSERT INTO municipios (nome, uf)
    VALUES ('Vitória', 'ES')
    RETURNING id INTO municipio_id_local;
  END IF;

  FOR registro IN SELECT value FROM jsonb_array_elements(p_registros)
  LOOP
    praia_id_local := NULL;

    IF registro->>'tipo_ponto' = 'praia' THEN
      INSERT INTO praias (municipio_id, nome)
      VALUES (municipio_id_local, registro->>'praia')
      ON CONFLICT (municipio_id, nome) DO UPDATE SET nome = EXCLUDED.nome
      RETURNING id INTO praia_id_local;
    END IF;

    INSERT INTO pontos_monitoramento (
      municipio_id, praia_id, codigo, descricao, tipo_ponto, utm_e, utm_s
    )
    VALUES (
      municipio_id_local,
      praia_id_local,
      registro->>'codigo',
      registro->>'descricao',
      registro->>'tipo_ponto',
      NULLIF(registro->>'utm_e', '')::numeric,
      NULLIF(registro->>'utm_s', '')::numeric
    )
    ON CONFLICT (municipio_id, codigo, tipo_ponto) DO UPDATE SET
      praia_id = EXCLUDED.praia_id,
      descricao = EXCLUDED.descricao,
      utm_e = EXCLUDED.utm_e,
      utm_s = EXCLUDED.utm_s
    RETURNING id INTO ponto_id_local;

    SELECT EXISTS (
      SELECT 1
      FROM amostras_balneabilidade
      WHERE fonte_id = fonte_id_local
        AND id_amostra = registro->>'id_amostra'
    ) INTO amostra_existente;

    IF amostra_existente THEN
      ignorados := ignorados + 1;
    ELSE
      INSERT INTO amostras_balneabilidade (
        fonte_id, documento_fonte_id, ponto_id, id_amostra, id_relatorio,
        pagina, data_coleta, hora_coleta, algas, banhistas, lixo,
        condicoes_meteorologicas_24h, condicoes_meteorologicas_momento,
        data_publicacao, temperatura_ambiente, coliformes_nmp_100ml,
        plano_amostragem, laboratorio, problemas_validacao
      )
      VALUES (
        fonte_id_local, documento_id_local, ponto_id_local, registro->>'id_amostra',
        registro->>'id_relatorio', NULLIF(registro->>'pagina', '')::integer,
        (registro->>'data_coleta')::date, NULLIF(registro->>'hora_coleta', '')::time,
        NULLIF(registro->>'algas', '')::boolean, NULLIF(registro->>'banhistas', '')::boolean,
        NULLIF(registro->>'lixo', '')::boolean,
        registro->>'condicoes_meteorologicas_24h',
        registro->>'condicoes_meteorologicas_momento',
        NULLIF(registro->>'data_publicacao', '')::timestamptz,
        NULLIF(registro->>'temperatura_ambiente', '')::numeric,
        NULLIF(registro->>'coliformes_nmp_100ml', '')::numeric,
        registro->>'plano_amostragem', registro->>'laboratorio',
        registro->>'problemas_validacao'
      );
      inseridos := inseridos + 1;
    END IF;
  END LOOP;

  RETURN jsonb_build_object(
    'registros_recebidos', jsonb_array_length(p_registros),
    'registros_inseridos', inseridos,
    'registros_ignorados', ignorados,
    'registros_rejeitados', 0,
    'arquivo', p_nome_arquivo
  );
END;
$$;

REVOKE ALL ON FUNCTION importar_amostras_csv(jsonb, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION importar_amostras_csv(jsonb, text) TO service_role;
